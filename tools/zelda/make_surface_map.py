#!/usr/bin/env python3
"""
Zelda 64 port: writes zelda/maps/zl_surfaces.map, a room for walking on each kind of floor.

Compile it like zl_test (linux/compile_map.sh zl_surfaces) and start it with +map zl_surfaces.

What's in it:
  - six lanes of floor running east from the start, each one a texture that Half-Life's
    sound/materials.txt files under a material PMZ_Surface (pm_shared/pm_zelda.c) turns into an
    OoT floor: stone, dirt, sand, grass, wood, and shallow water (a func_water two units under
    the floor, so Link wades through it with his feet wet: waterlevel 1)
  - past them an ice rink (glass is ice, FLOOR_TYPE_5) with pillars to steer round, where Link
    slides like on the Ice Cavern floors (PMZ_IceSlide)
  - signs at both ends saying which lane is which

Jabu-Jabu's floor is left out: it needs a flesh texture, and halflife.wad has none in materials.txt.
"""

import os

from make_test_map import box, entity

TEX_STONE = "GENERIC015V"
TEX_WALL = "GENERIC028"
TEX_WATER = "!WATERBLUE"

# Lanes from south to north: name, floor texture, floor height
LANES = [
    ("stone", "GENERIC015V", 0),
    ("dirt", "OUT_DIRT1", 0),
    ("sand", "OUT_SND1", 0),
    ("grass", "-0OUT_GRSS1", 0),
    ("wood", "CRATE01", 0),
    ("water", "OUT_GRVL2", -16),
]
TEX_ICE = "GLASSBLUE1"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "..", "zelda", "maps", "zl_surfaces.map")

    W, D, H = 2560, 1280, 384      # room size
    T = 16                          # wall thickness
    BOTTOM = -64                    # floors are solid down to here
    LANE_X0, LANE_X1 = 256, 1280    # the lanes run along x
    LANE_W = 200
    LANE_Y0 = (D - LANE_W * len(LANES)) // 2
    ICE_X0 = 1408                   # the rink runs from here to the east wall

    world = []

    # Shell
    world.append(box((-T, -T, H), (W + T, D + T, H + T), TEX_WALL))                     # ceiling
    world.append(box((-T, -T, BOTTOM - T), (W + T, D + T, BOTTOM), TEX_WALL))           # under everything
    world.append(box((-T, -T, BOTTOM), (0, D + T, H), TEX_WALL))                        # west
    world.append(box((W, -T, BOTTOM), (W + T, D + T, H), TEX_WALL))                     # east
    world.append(box((0, -T, BOTTOM), (W, 0, H), TEX_WALL))                             # south
    world.append(box((0, D, BOTTOM), (W, D + T, H), TEX_WALL))                          # north

    # Stone around the lanes: the start, the strip between lanes and rink, and the margins
    world.append(box((0, 0, BOTTOM), (LANE_X0, D, 0), TEX_STONE))
    world.append(box((LANE_X1, 0, BOTTOM), (ICE_X0, D, 0), TEX_STONE))
    world.append(box((LANE_X0, 0, BOTTOM), (LANE_X1, LANE_Y0, 0), TEX_STONE))
    world.append(box((LANE_X0, LANE_Y0 + LANE_W * len(LANES), BOTTOM), (LANE_X1, D, 0), TEX_STONE))

    ents = []
    water = []
    for i, (name, tex, z) in enumerate(LANES):
        y0 = LANE_Y0 + i * LANE_W
        world.append(box((LANE_X0, y0, BOTTOM), (LANE_X1, y0 + LANE_W, z), TEX_STONE, top=tex))
        if z < 0:
            # Shallow water: Link's feet are in it (waterlevel 1), his waist isn't
            water.append(box((LANE_X0, y0, z), (LANE_X1, y0 + LANE_W, -2), TEX_WATER))

    # The rink, with two pillars to slide round and a low wall to slide into
    world.append(box((ICE_X0, 0, BOTTOM), (W, D, 0), TEX_STONE, top=TEX_ICE))
    world.append(box((1792, 384, 0), (1856, 448, H), TEX_WALL))
    world.append(box((2112, 832, 0), (2176, 896, H), TEX_WALL))
    world.append(box((2368, 160, 0), (2384, 544, 32), TEX_WALL))

    ents.append(entity("worldspawn", {
        "wad": "\\half-life\\valve\\halflife.wad;\\half-life\\valve\\liquids.wad;\\half-life\\valve\\xeno.wad",
        "message": "Zelda 64 surfaces",
        "skyname": "desert",
        "mapversion": "220",
    }, world))

    ents.append(entity("info_player_start", {"origin": f"128 {D // 2} 36", "angles": "0 0 0"}))

    for x in range(320, W, 512):
        for y in (320, 960):
            ents.append(entity("light", {"origin": f"{x} {y} {H - 48}", "_light": "255 240 220 260"}))

    for b in water:
        ents.append(entity("func_water", {"skin": "-3", "WaveHeight": "0", "rendermode": "2", "renderamt": "160"}, [b]))

    ents.append(entity("zl_sign", {"origin": f"192 {LANE_Y0 - 16} 0", "angles": "0 0 0", "message": "SIGN_ZL_SURFACES"}))
    ents.append(entity("zl_sign", {"origin": f"{ICE_X0 - 64} {D // 2 + 96} 0", "angles": "0 0 0", "message": "SIGN_ZL_ICE"}))

    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/zelda/make_surface_map.py\n")
        for e in ents:
            f.write(e)
    print(f"wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
